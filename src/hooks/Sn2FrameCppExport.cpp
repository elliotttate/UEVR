void on_draw_indexed_instanced(ID3D12GraphicsCommandList*,
                               UINT idx, UINT inst, UINT si, INT bv, UINT sii) {
    if (!is_recording()) return;
    auto& s = state();
    std::scoped_lock _{s.mu};
    Event e{Chunk::DrawIndexed};
    e.v[0] = idx; e.v[1] = inst; e.v[2] = si; e.v[3] = static_cast<uint32_t>(bv); e.v[4] = sii;
    s.events.push_back(e);
}

