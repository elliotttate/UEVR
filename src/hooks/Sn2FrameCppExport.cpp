void on_present() {
    if (!env_enabled()) return;
    auto& s = state();
    const auto n = s.present_count.fetch_add(1, std::memory_order_relaxed) + 1;

    // If we're recording, this Present ends the captured frame.
    if (s.recording.load(std::memory_order_acquire)) {
        {
            std::scoped_lock _{s.mu};
            Event e{Chunk::Present};
            s.events.push_back(e);
        }
        emit_capture();
        return;
    }

    // Check trigger: armed via API, OR auto-arm at frame N.
    if (n == trigger_frame() || s.armed.load(std::memory_order_acquire)) {
        s.recording.store(true, std::memory_order_release);
        SPDLOG_WARN("[SN2-FrameCppExport] arming capture at present #{}", n);
    }
}

